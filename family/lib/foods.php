/** 입력 화면용 음식 목록: 우리집 음식(자주 먹은 순) + 기본 목록 */
function food_choices(): array
{
    $mine = db()->query('SELECT name, amount, kcal, carbs, protein, fat, sodium, uses FROM foods ORDER BY uses DESC, last_used DESC')->fetchAll();
    $names = [];
    $out = [];
    foreach ($mine as $f) {
        $names[$f['name']] = true;
        $out[] = ['name' => $f['name'], 'amount' => $f['amount'], 'kcal' => (float) $f['kcal'], 'carbs' => (float) $f['carbs'],
            'protein' => (float) $f['protein'], 'fat' => (float) $f['fat'], 'sodium' => (float) $f['sodium'], 'mine' => true, 'uses' => (int) $f['uses']];
    }
    foreach (BUILTIN_FOODS as [$name, $amount, $kcal, $carbs, $protein, $fat, $sodium]) {
        if (isset($names[$name])) continue;
        $out[] = compact('name', 'amount', 'kcal', 'carbs', 'protein', 'fat', 'sodium') + ['mine' => false, 'uses' => 0];
    }
    return $out;
}

/** 저장할 때 우리집 음식 목록에 기억 (같은 이름이면 최신 영양 정보로) */
function remember_food(array $item): void
{
    db()->prepare('INSERT INTO foods (name, amount, kcal, carbs, protein, fat, sodium, uses, last_used) VALUES (?, ?, ?, ?, ?, ?, ?, 1, NOW())
        ON DUPLICATE KEY UPDATE amount = VALUES(amount), kcal = VALUES(kcal), carbs = VALUES(carbs), protein = VALUES(protein),
        fat = VALUES(fat), sodium = VALUES(sodium), uses = uses + 1, last_used = NOW()')
        ->execute([$item['name'], $item['amount'], $item['kcal'], $item['carbs'], $item['protein'], $item['fat'], $item['sodium']]);
}

/** 한 끼의 음식 목록과 합계 */
function meal_items(int $mealId): array
{
    $stmt = db()->prepare('SELECT * FROM meal_items WHERE meal_id = ? ORDER BY sort, id');
    $stmt->execute([$mealId]);
    return $stmt->fetchAll();
}

function items_total(array $items): array
{
    $t = ['kcal' => 0, 'carbs' => 0, 'protein' => 0, 'fat' => 0, 'sodium' => 0];
    foreach ($items as $i) foreach ($t as $k => $_) $t[$k] += (float) $i[$k] * (float) $i['servings'];
    return $t;
}

function meal_type_for_now(): string
{
    $h = (int) date('G');
    return $h >= 4 && $h < 10 ? 'breakfast' : ($h < 15 && $h >= 10 ? 'lunch' : ($h >= 15 && $h < 17 ? 'snack' : ($h >= 17 && $h < 21 ? 'dinner' : 'late')));
}
